# QUESTÃO 07 - Faça um Programa que pergunte quanto você ganha por hora e o número de horas trabalhadas no mês. Calcule e mostre o total do seu salário no referido mês.

ganha = float(input('Quanto você ganha por hora: '))
horas = int(input('Número de horas que você trabalhou no mês: '))
x = ganha*horas
print('O seu salário no referido mês é:', x,'reais')